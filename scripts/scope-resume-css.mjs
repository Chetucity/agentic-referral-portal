/**
 * Scopes the resume builder's stylesheet so it cannot leak into the rest of
 * the portal.
 *
 * The builder arrived as a standalone Vite app and styles bare elements —
 * `body`, `input`, `button`, `label`, `h1`…`h6` — which would fight Tailwind
 * everywhere else in the app the moment the route's CSS chunk loaded. Every
 * rule is therefore rewritten to sit under a single `.rb` root:
 *
 *     body            ->  .rb
 *     input, textarea ->  .rb input, .rb textarea
 *     .panel          ->  .rb .panel
 *     :root           ->  .rb          (custom properties still cascade down)
 *
 * Keyframes, font-face and custom-property declarations are left alone.
 *
 *   node scripts/scope-resume-css.mjs <source.css> <dest.css>
 */
import { readFileSync, writeFileSync } from "node:fs";
import postcss from "postcss";

const ROOT = ".rb";

// Selectors that mean "the page itself" collapse onto the root element.
const ROOT_LIKE = new Set(["html", "body", ":root", "*", ":host"]);

function scopeSelector(sel) {
  const s = sel.trim();
  if (!s) return s;

  // Already scoped (idempotent re-runs).
  if (s === ROOT || s.startsWith(`${ROOT} `) || s.startsWith(`${ROOT}.`)) return s;

  // `body`, `:root`, `*` and friends — with or without trailing pseudo parts,
  // e.g. `*::-webkit-scrollbar` or `*, *::before`.
  for (const base of ROOT_LIKE) {
    if (s === base) return ROOT;
    if (s.startsWith(base + "::") || s.startsWith(base + ":")) {
      return ROOT + s.slice(base.length);
    }
    if (s.startsWith(base + " ")) {
      return `${ROOT} ${s.slice(base.length + 1)}`;
    }
  }

  return `${ROOT} ${s}`;
}

const [, , src, dest] = process.argv;
if (!src || !dest) {
  console.error("usage: node scripts/scope-resume-css.mjs <source.css> <dest.css>");
  process.exit(1);
}

const root = postcss.parse(readFileSync(src, "utf8"));

root.walkRules((rule) => {
  // Rules inside @keyframes are percentages / from / to, not selectors.
  const parent = rule.parent;
  if (parent && parent.type === "atrule" && /keyframes/i.test(parent.name)) return;

  rule.selectors = rule.selectors.map(scopeSelector);
});

const banner = `/* Resume builder styles — generated by scripts/scope-resume-css.mjs.
   Every selector is scoped under .rb so these rules cannot escape the
   /resume route. Edit the source stylesheet and re-run the script rather
   than editing this file. */\n\n`;

writeFileSync(dest, banner + root.toString());
console.log(`scoped ${root.nodes.length} top-level nodes -> ${dest}`);
